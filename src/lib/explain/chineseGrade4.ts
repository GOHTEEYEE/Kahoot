export function formatChineseGrade4(
  id: string,
  prompt: string,
  options: string[],
  correctIndex: number,
  chosen: string,
  isCorrect: boolean,
): string | null {
  const tip = CHINESE_GRADE4_TIPS[id];
  if (!tip) return null;

  const correct = options[correctIndex] ?? "";
  const lines: string[] = [];

  if (isCorrect) {
    lines.push(`✅ 答对了！这题考的是「${tip.skill}」。`);
  } else {
    lines.push(`❌ 你选了「${chosen}」，正确答案是「${correct}」。`);
    lines.push(`题目：${prompt}`);
    lines.push(`这题考的是「${tip.skill}」。`);
  }

  lines.push("");
  lines.push(`📌 为什么选「${correct}」`);
  lines.push(tip.why);
  lines.push("");
  lines.push("🔍 四个选项逐一说明：");
  options.forEach((opt, i) => {
    const mark = i === correctIndex ? "✅" : "❌";
    const note = tip.others[i] ?? "";
    lines.push(`${mark} 「${opt}」：${note}`);
  });

  return lines.join("\n");
}
